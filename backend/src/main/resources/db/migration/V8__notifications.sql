-- V8: notifications (step N3 of Documentation/nothing-fake-brief.md).
--
-- The bell in the top bar used to show a number typed into the code. These two
-- tables are what it counts now.
--
-- notifications: one row per thing that happened and is worth telling people.
--
--   kind                 item_86    an item was 86'd
--                        item_back  an 86'd item is back on
--                        order_up   everything sent on a check has been made
--                        message    someone in the kitchen, behind the bar, or a
--                                   manager wrote one
--   body                 the words shown ("Garden Toast is 86'd")
--   recipient_staff_id   who it is for. NULL means everyone. Only "order up"
--                        names one person: whoever opened the check.
--   created_by_staff_id  who caused it. That person is not shown it: they know.
--   created_by_name      a copy of their name, shown on a message ("Kit: ...")
--   created_at           when. A notification is listed for 24 hours.
--
-- notification_dismissals: who has dismissed what. One row per person per
-- notification, so dismissing is per person (the bartender dismissing "Garden
-- Toast is 86'd" does not take it off the servers' lists) and follows the person
-- from terminal to terminal, because it is kept here and not on the device.
-- The primary key is the pair, which also makes dismissing twice harmless.
--
-- Like the other tables, staff IDs are plain columns with no foreign key, and
-- the name is a copy, so a row still reads correctly after that person has left.
-- Moments are timestamptz (the same in every time zone), as every table added
-- since V4 uses.
--
-- Both tables start EMPTY: a restaurant has no notifications until something
-- happens.

CREATE TABLE notifications (
    notification_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                 varchar(20)  NOT NULL,
    body                 varchar(300) NOT NULL,
    recipient_staff_id   bigint,
    created_by_staff_id  bigint,
    created_by_name      varchar(50),
    created_at           timestamptz  NOT NULL
);

-- Every request for someone's notifications asks for "the last 24 hours"
CREATE INDEX notifications_created_at ON notifications (created_at);

CREATE TABLE notification_dismissals (
    notification_id  bigint      NOT NULL,
    staff_id         bigint      NOT NULL,
    dismissed_at     timestamptz NOT NULL,
    PRIMARY KEY (notification_id, staff_id)
);
