-- V9: challenges (step N5 of Documentation/nothing-fake-brief.md).
--
-- The Challenges screen used to show invented challenges typed into the code.
-- These two tables hold the real ones.
--
-- challenges: one row per challenge a manager has made.
--
--   name, description    what it is called and, optionally, a line about it
--   measure              what is counted, for each person, on the checks closed
--                        between starts_at and ends_at:
--                          items_sold     how many items (of one category or one item)
--                          total_sales    sales before tax
--                          check_average  sales divided by checks
--                          biggest_check  the largest single check
--   target               what a person has to reach: a number of items, or dollars
--   menu_category,       for items_sold only, and exactly one of the two: the
--   menu_item_id         category whose items count, or the one item that counts
--   min_checks           for check_average only: how many checks a person needs
--                        before their average counts, so one large check cannot win
--   starts_at, ends_at   the challenge's period
--   prize                optional words a manager writes ("$20", "first cut Friday").
--                        The app pays nothing; a manager hands it over.
--   created_by_...       who made it (a copy of the name, as elsewhere)
--
-- THERE IS NO PROGRESS COLUMN, ON PURPOSE. How far each person has got is worked
-- out from the checks every time it is asked for. A stored count could drift
-- from the checks; a computed one cannot. Nobody joins a challenge either, so
-- there is no table of participants: everyone who opens checks in its period is
-- in it.
--
-- challenge_awards: a prize was handed over. This IS stored, because it is a
-- fact and not a sum: which challenge, which person, which manager marked it,
-- and when. One row per person per challenge (the UNIQUE constraint), so marking
-- the same person twice changes nothing.
--
-- challenge_id in challenge_awards is a FOREIGN KEY: PostgreSQL refuses to
-- delete a challenge that has an award. The app refuses first, with words a
-- manager can read (ChallengeService.delete); this is the net under it, in the
-- way the index orders_one_open_per_table is the net under "one open check per
-- table". It is the first foreign key in this schema. Staff IDs stay plain
-- columns with a copy of the name, like every other table.
--
-- Moments are timestamptz, as every table added since V4 uses. The checks a
-- challenge counts are stamped with local times (orders.closed_at); the app
-- converts between the two (RestaurantTime).
--
-- Both tables start EMPTY: a restaurant has no challenges until a manager makes one.

CREATE TABLE challenges (
    challenge_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 varchar(60)   NOT NULL,
    description          varchar(300),
    measure              varchar(20)   NOT NULL,
    target               numeric(10,2) NOT NULL,
    menu_category        varchar(50),
    menu_item_id         bigint,
    min_checks           integer,
    starts_at            timestamptz   NOT NULL,
    ends_at              timestamptz   NOT NULL,
    prize                varchar(100),
    created_by_staff_id  bigint        NOT NULL,
    created_by_name      varchar(50)   NOT NULL,
    created_at           timestamptz   NOT NULL,
    CONSTRAINT challenges_end_after_start CHECK (ends_at > starts_at),
    CONSTRAINT challenges_target_above_zero CHECK (target > 0)
);

-- The screen asks for "the ones still running or coming" and "the last few that ended"
CREATE INDEX challenges_ends_at ON challenges (ends_at);

CREATE TABLE challenge_awards (
    challenge_award_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id         bigint      NOT NULL REFERENCES challenges (challenge_id),
    staff_id             bigint      NOT NULL,
    staff_name           varchar(50) NOT NULL,
    awarded_by_staff_id  bigint      NOT NULL,
    awarded_by_name      varchar(50) NOT NULL,
    awarded_at           timestamptz NOT NULL,
    CONSTRAINT challenge_awards_one_per_person UNIQUE (challenge_id, staff_id)
);
