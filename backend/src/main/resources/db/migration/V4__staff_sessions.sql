-- V4: sessions move from the backend's memory into the database.
--
-- A "session" is the backend remembering that a person signed in. Until now the
-- list lived in the running program, so restarting the backend signed the whole
-- floor out. One row here is one signed-in person on one device.
--
-- WHAT IS STORED IS A HASH OF THE TOKEN, NOT THE TOKEN.
--   After a PIN is accepted the device is handed a long random "token" and sends
--   it with every request. If this table held tokens, anyone who got a copy of
--   the database (a backup, a dump for a bug report) could send one and act as
--   that person. A hash can be checked against a token but cannot be turned back
--   into one, so a copy of this table signs nobody in.
--   The hash is SHA-256, written as 64 hex characters.
--
-- name, role, and must_change_pin are copied from the staff row at sign-in, so
-- a request is identified by reading one row. StaffService ends or updates a
-- person's sessions whenever it changes one of those on the staff row.
--
-- The two times are "timestamptz": a moment in time, stored the same whatever
-- time zone the server is set to. (The older tables use plain "timestamp",
-- which is a known gap; a 12-hour idle limit must not shift by an hour when the
-- clocks change.)
--
-- Like the other tables, staff_id is a plain ID column with no foreign key.

CREATE TABLE staff_sessions (
    session_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash      varchar(64)  NOT NULL,
    staff_id        bigint       NOT NULL,
    name            varchar(50)  NOT NULL,
    role            varchar(20)  NOT NULL,
    must_change_pin boolean      NOT NULL DEFAULT false,
    created_at      timestamptz  NOT NULL,
    last_used_at    timestamptz  NOT NULL
);

-- Every request looks its session up by the hash of its token, so this lookup
-- must be an index, and no two sessions may share a hash.
CREATE UNIQUE INDEX staff_sessions_token_hash ON staff_sessions (token_hash);

-- "Sign this person out everywhere" (their PIN or role changed) finds rows by staff_id.
CREATE INDEX staff_sessions_staff_id ON staff_sessions (staff_id);
