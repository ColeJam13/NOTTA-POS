-- ============================================================================
-- V1: baseline - the schema as it stood when Flyway was adopted (2026-11-20)
-- ============================================================================
-- WHAT: Every table the app had at that point, exactly as it existed in the
--       owner's database.
-- WHY:  Until now Hibernate created and altered tables by itself at start-up
--       (ddl-auto=update). From here on the schema changes only through the
--       numbered files in this folder, so every database goes through the
--       same steps in the same order.
--
-- HOW THIS FILE IS USED:
--   - On a brand-new, empty database Flyway RUNS this file, then V2, V3, ...
--   - On a database that already has these tables (the owner's), Flyway does
--     NOT run it. It records "already at V1" and continues from V2. That is
--     the "baseline" setting in application.properties.
--
-- NEVER EDIT THIS FILE. Flyway stores a checksum of every migration it has run
-- and refuses to start if a file changed afterwards. To change the schema, add
-- a new file with the next number.
--
-- Two things here look old-fashioned on purpose, because they match the real
-- database this was taken from:
--   - Most ID columns are "bigserial" (a number handed out by a sequence).
--     Those tables were created under an earlier Hibernate. Only "staff", the
--     newest table, uses the newer "generated by default as identity". Both do
--     the same job.
--   - tables.is_quick_order has no default yet. V2 adds it.
--
-- Tables are linked by plain ID columns. There are no foreign keys.
-- ============================================================================

CREATE TABLE prep_stations (
    is_active       boolean      NOT NULL,
    created_at      timestamp(6) NOT NULL,
    prep_station_id bigserial    PRIMARY KEY,
    name            varchar(50)  NOT NULL UNIQUE,
    description     varchar(200)
);

CREATE TABLE menu_items (
    is_active       boolean        NOT NULL,
    price           numeric(10,2)  NOT NULL,
    created_at      timestamp(6)   NOT NULL,
    menu_item_id    bigserial      PRIMARY KEY,
    prep_station_id bigint,
    category        varchar(50)    NOT NULL,
    name            varchar(100)   NOT NULL,
    description     varchar(500),
    is_86d          boolean        DEFAULT false NOT NULL
);

CREATE TABLE modifier_groups (
    is_active         boolean      NOT NULL,
    is_required       boolean      NOT NULL,
    max_selections    integer      NOT NULL,
    created_at        timestamp(6) NOT NULL,
    modifier_group_id bigserial    PRIMARY KEY,
    name              varchar(100) NOT NULL,
    description       varchar(200)
);

CREATE TABLE modifiers (
    is_active         boolean       NOT NULL,
    price_adjustment  numeric(10,2),
    created_at        timestamp(6)  NOT NULL,
    modifier_group_id bigint        NOT NULL,
    modifier_id       bigserial     PRIMARY KEY,
    name              varchar(100)  NOT NULL
);

CREATE TABLE menu_item_modifier_groups (
    created_at                  timestamp(6) NOT NULL,
    menu_item_id                bigint       NOT NULL,
    menu_item_modifier_group_id bigserial    PRIMARY KEY,
    modifier_group_id           bigint       NOT NULL
);

CREATE TABLE tables (
    is_quick_order boolean,
    rotation       integer,
    seat_count     integer      NOT NULL,
    x_position     integer,
    y_position     integer,
    created_at     timestamp(6) NOT NULL,
    table_id       bigserial    PRIMARY KEY,
    table_number   varchar(10)  NOT NULL UNIQUE,
    section        varchar(20),
    shape          varchar(20),
    status         varchar(20)  NOT NULL,
    server_name    varchar(50)
);

CREATE TABLE table_status_logs (
    created_at timestamp(6) NOT NULL,
    log_id     bigserial    PRIMARY KEY,
    table_id   bigint       NOT NULL,
    new_status varchar(20)  NOT NULL,
    old_status varchar(20),
    changed_by varchar(100)
);

CREATE TABLE orders (
    subtotal    numeric(10,2),
    tax         numeric(10,2),
    total       numeric(10,2),
    closed_at   timestamp(6),
    created_at  timestamp(6) NOT NULL,
    order_id    bigserial    PRIMARY KEY,
    table_id    bigint       NOT NULL,
    order_type  varchar(20)  NOT NULL,
    status      varchar(20)  NOT NULL,
    server_name varchar(50),
    staff_id    bigint
);

CREATE TABLE order_items (
    delay_seconds        integer       NOT NULL,
    is_locked            boolean       NOT NULL,
    price                numeric(10,2) NOT NULL,
    quantity             integer       NOT NULL,
    completed_at         timestamp(6),
    created_at           timestamp(6)  NOT NULL,
    delay_expires_at     timestamp(6),
    fired_at             timestamp(6),
    menu_item_id         bigint        NOT NULL,
    order_id             bigint        NOT NULL,
    order_item_id        bigserial     PRIMARY KEY,
    sent_at              timestamp(6),
    status               varchar(20)   NOT NULL,
    special_instructions varchar(500)
);

CREATE TABLE order_item_modifiers (
    price_adjustment       numeric(10,2),
    created_at             timestamp(6) NOT NULL,
    modifier_id            bigint       NOT NULL,
    order_item_id          bigint       NOT NULL,
    order_item_modifier_id bigserial    PRIMARY KEY
);

CREATE TABLE payments (
    amount                numeric(10,2) NOT NULL,
    tip_amount            numeric(10,2),
    created_at            timestamp(6)  NOT NULL,
    order_id              bigint        NOT NULL,
    payment_id            bigserial     PRIMARY KEY,
    status                varchar(20)   NOT NULL,
    payment_method        varchar(50)   NOT NULL,
    transaction_reference varchar(100)
);

CREATE TABLE staff (
    staff_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) NOT NULL,
    is_active  boolean      NOT NULL,
    name       varchar(50)  NOT NULL,
    pin_hash   varchar(100) NOT NULL,
    role       varchar(20)  NOT NULL
);
